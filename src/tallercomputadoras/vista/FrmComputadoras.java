    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String codigo = txtCodigo.getText().trim()
                .toUpperCase(java.util.Locale.ROOT);

        String marca = txtMarca.getText().trim();
        String modelo = txtModelo.getText().trim();
        String falla = txtFalla.getText().trim();
        String cliente = txtCliente.getText().trim();
        String telefono = txtTelefono.getText().trim();

        if (codigo.isEmpty() || marca.isEmpty() || modelo.isEmpty()
                || falla.isEmpty() || cliente.isEmpty()
                || telefono.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Completa todos los campos.",
                    "Datos incompletos",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Computadora computadora = new Computadora(
                codigo, marca, modelo, falla, cliente, telefono
        );

        try {
            arreglo.insertar(computadora);
        } catch (IllegalArgumentException | IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "No se pudo registrar",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        mostrarComputadoras();
        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Computadora registrada correctamente."
        );        // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Selecciona una computadora o escribe su código."
            );
            return;
        }

        boolean eliminado = arreglo.eliminar(codigo);

        if (!eliminado) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No existe una computadora con ese código."
            );
            return;
        }

        mostrarComputadoras();
        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Computadora eliminada correctamente."
        );        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed

