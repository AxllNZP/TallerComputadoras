    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
if (tblComputadoras.getSelectedRow() == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecciona la computadora que deseas actualizar."
    );
    return;
}

String codigo = txtCodigo.getText().trim();
String marca = txtMarca.getText().trim();
String modelo = txtModelo.getText().trim();
String falla = txtFalla.getText().trim();
String cliente = txtCliente.getText().trim();
String telefono = txtTelefono.getText().trim();

if (codigo.isEmpty() || marca.isEmpty() || modelo.isEmpty()
        || falla.isEmpty() || cliente.isEmpty()
        || telefono.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Completa todos los campos.",
            "Datos incompletos",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

boolean actualizado = arreglo.actualizar(
        codigo, marca, modelo, falla, cliente, telefono
);

if (!actualizado) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "No existe una computadora con ese código."
    );
    return;
}

mostrarComputadoras();
limpiarCampos();

javax.swing.JOptionPane.showMessageDialog(
        this,
        "Computadora actualizada correctamente."
);        // TODO add your handling code here:
    }//GEN-LAST:event_btnActualizarActionPerformed

