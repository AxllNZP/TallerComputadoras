    private void configurarTabla() {
        String[] columnas = {
            "Código", "Marca", "Modelo",
            "Falla reportada", "Cliente", "Teléfono"
        };

        modeloTabla = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        tblComputadoras.setModel(modeloTabla);
        tblComputadoras.setSelectionMode(
                javax.swing.ListSelectionModel.SINGLE_SELECTION
        );

        tblComputadoras.getTableHeader().setReorderingAllowed(false);

        tblComputadoras.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                cargarSeleccion();
            }
        });
    }

    private void limpiarCampos() {
        tblComputadoras.clearSelection();

        txtCodigo.setEditable(true);
        txtCodigo.setText("");
        txtMarca.setText("");
        txtModelo.setText("");
        txtFalla.setText("");
        txtCliente.setText("");
        txtTelefono.setText("");

        txtCodigo.requestFocusInWindow();
    }

    private void cargarSeleccion() {
        int fila = tblComputadoras.getSelectedRow();

        if (fila == -1) {
            return;
        }

        int posicion = tblComputadoras.convertRowIndexToModel(fila);
        Computadora computadora = arreglo.obtener(posicion);

        txtCodigo.setText(computadora.getCodigo());
        txtMarca.setText(computadora.getMarca());
        txtModelo.setText(computadora.getModelo());
        txtFalla.setText(computadora.getFalla());
        txtCliente.setText(computadora.getCliente());
        txtTelefono.setText(computadora.getTelefono());

        txtCodigo.setEditable(false);
    }

    private void mostrarComputadoras() {
        modeloTabla.setRowCount(0);

        for (int i = 0; i < arreglo.getCantidad(); i++) {
            Computadora computadora = arreglo.obtener(i);

            modeloTabla.addRow(new Object[]{
                computadora.getCodigo(),
                computadora.getMarca(),
                computadora.getModelo(),
                computadora.getFalla(),
                computadora.getCliente(),
                computadora.getTelefono()
            });
        }
    }

