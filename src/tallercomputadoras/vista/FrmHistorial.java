    private void configurarTabla() {
        String[] columnas = {"Posición", "Estado anterior"};

        modeloTabla = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        tblHistorial.setModel(modeloTabla);
        tblHistorial.getTableHeader().setReorderingAllowed(false);
    }

    private void mostrarFicha() {
        lblCodigo.setText("Código: " + ficha.getCodigo());
        lblCliente.setText("Cliente: " + ficha.getCliente());
        lblEquipo.setText("Equipo: " + ficha.getEquipo());
        lblEstado.setText("Estado actual: " + ficha.getEstado());

        btnAvanzar.setEnabled(ficha.puedeAvanzar());
    }

    private void mostrarHistorial() {
        modeloTabla.setRowCount(0);

        NodoEstado actual = pila.getCima();
        int posicion = 1;

        while (actual != null) {
            modeloTabla.addRow(new Object[]{
                posicion == 1 ? "1 — Cima" : String.valueOf(posicion),
                actual.getEstado()
            });

            actual = actual.getSiguiente();
            posicion++;
        }
    }

