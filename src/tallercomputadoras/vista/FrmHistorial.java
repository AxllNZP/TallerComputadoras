    private void btnAvanzarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAvanzarActionPerformed
        if (!ficha.puedeAvanzar()) {
            JOptionPane.showMessageDialog(
                    this, "La ficha ya está en Entregado."
            );
            return;
        }

        pila.apilar(ficha.getEstado());
        ficha.avanzar();

        mostrarFicha();
        mostrarHistorial();        // TODO add your handling code here:
    }//GEN-LAST:event_btnAvanzarActionPerformed

    private void btnDeshacerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeshacerActionPerformed
        String estadoAnterior = pila.desapilar();

        if (estadoAnterior == null) {
            JOptionPane.showMessageDialog(
                    this, "No hay cambios para deshacer."
            );
            return;
        }

        ficha.restaurarEstado(estadoAnterior);

        mostrarFicha();
        mostrarHistorial();        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeshacerActionPerformed

