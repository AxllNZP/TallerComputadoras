    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
String codigo = txtCodigo.getText().trim()
        .toUpperCase(java.util.Locale.ROOT);

String cliente = txtCliente.getText().trim();
String equipo = txtEquipo.getText().trim();
String falla = txtFalla.getText().trim();
int indicePrioridad = cmbPrioridad.getSelectedIndex();

if (codigo.isEmpty() || cliente.isEmpty()
        || equipo.isEmpty() || falla.isEmpty()
        || indicePrioridad == -1) {

    JOptionPane.showMessageDialog(
            this, "Completa todos los campos."
    );
    return;
}

int prioridad = indicePrioridad + 1;

try {
    AtencionDiagnostico atencion = new AtencionDiagnostico(
            codigo, cliente, equipo, falla, prioridad
    );

    cola.encolar(atencion);

} catch (IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this, ex.getMessage());
    return;
}

mostrarCola();
limpiarCampos();

JOptionPane.showMessageDialog(
        this, "Equipo ingresado a la cola."
);        // TODO add your handling code here:
    }//GEN-LAST:event_btnIngresarActionPerformed

    private void btnAtenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtenderActionPerformed
AtencionDiagnostico atendido = cola.atender();

if (atendido == null) {
    JOptionPane.showMessageDialog(
            this, "No hay equipos pendientes de atención."
    );
    return;
}

mostrarCola();

JOptionPane.showMessageDialog(
        this,
        "Equipo retirado para diagnóstico:\n"
        + "Código: " + atendido.getCodigo() + "\n"
        + "Cliente: " + atendido.getCliente() + "\n"
        + "Equipo: " + atendido.getEquipo() + "\n"
        + "Falla: " + atendido.getFalla() + "\n"
        + "Prioridad: " + atendido.getPrioridadTexto()
);        // TODO add your handling code here:
    }//GEN-LAST:event_btnAtenderActionPerformed

