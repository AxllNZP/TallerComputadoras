    private void configurarTabla() {
        String[] columnas = {
            "Código", "Cliente", "Equipo", "Falla reportada", "Prioridad"
        };

        modeloTabla = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        tblAtenciones.setModel(modeloTabla);
        tblAtenciones.getTableHeader().setReorderingAllowed(false);
    }

    private void mostrarCola() {
        modeloTabla.setRowCount(0);

        NodoAtencion actual = cola.getPrimero();

        while (actual != null) {
            AtencionDiagnostico atencion = actual.getAtencion();

            modeloTabla.addRow(new Object[]{
                atencion.getCodigo(),
                atencion.getCliente(),
                atencion.getEquipo(),
                atencion.getFalla(),
                atencion.getPrioridadTexto()
            });

            actual = actual.getSiguiente();
        }
    }

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtCliente.setText("");
        txtEquipo.setText("");
        txtFalla.setText("");
        cmbPrioridad.setSelectedIndex(0);

        txtCodigo.requestFocusInWindow();
    }

