    private void btnPodarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPodarActionPerformed
        String id = txtIdPodar.getText().trim();
        
        if (id.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el ID del paso o solución a podar.");
            return;
        }
        
        boolean exito = arbol.podar(id);
        
        if (exito) {
            txtConsola.setText("--- RAMA '" + id.toUpperCase(java.util.Locale.ROOT) + "' PODADA CON ÉXITO ---\n\n");
            txtConsola.append("Toda la jerarquía dependiente de este nodo ha sido eliminada lógicamente.\n");
            txtConsola.append("Ejecuta un recorrido (Ej. Preorden) para verificar la nueva estructura.\n");
            txtIdPodar.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ningún nodo con ese ID en el árbol actual.");
        }
    }//GEN-LAST:event_btnPodarActionPerformed

