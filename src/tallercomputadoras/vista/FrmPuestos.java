    private void btnOcuparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOcuparActionPerformed
        int puesto = cmbPuesto.getSelectedIndex();
        int turno = cmbTurno.getSelectedIndex();

        if (puesto == -1 || turno == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona puesto y turno.");
            return;
        }

        if (!matriz.ocupar(puesto, turno)) {
            JOptionPane.showMessageDialog(
                    this, "Ese puesto ya está ocupado en el turno seleccionado."
            );
            return;
        }

        mostrarPuestos();
        JOptionPane.showMessageDialog(this, "Puesto ocupado correctamente.");        // TODO add your handling code here:
    }//GEN-LAST:event_btnOcuparActionPerformed

    private void btnLiberarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLiberarActionPerformed
        int puesto = cmbPuesto.getSelectedIndex();
        int turno = cmbTurno.getSelectedIndex();

        if (puesto == -1 || turno == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona puesto y turno.");
            return;
        }

        if (!matriz.liberar(puesto, turno)) {
            JOptionPane.showMessageDialog(
                    this, "Ese puesto ya está disponible en el turno seleccionado."
            );
            return;
        }

        mostrarPuestos();
        JOptionPane.showMessageDialog(this, "Puesto liberado correctamente.");        // TODO add your handling code here:
    }//GEN-LAST:event_btnLiberarActionPerformed

