    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String codigo = txtCodigo.getText().trim()
                .toUpperCase(java.util.Locale.ROOT);

        String cliente = txtCliente.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String equipo = txtEquipo.getText().trim();
        String falla = txtFalla.getText().trim();
        String estado = (String) cmbEstado.getSelectedItem();

        if (codigo.isEmpty() || cliente.isEmpty() || telefono.isEmpty()
                || equipo.isEmpty() || falla.isEmpty()
                || estado == null || estado.trim().isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Completa todos los campos.",
                    "Datos incompletos",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        OrdenReparacion orden = new OrdenReparacion(
                codigo, cliente, telefono, equipo, falla, estado
        );

        try {
            lista.insertar(orden);
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "No se pudo registrar",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        mostrarOrdenes();
        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Orden registrada correctamente."
        );        // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarActionPerformed

