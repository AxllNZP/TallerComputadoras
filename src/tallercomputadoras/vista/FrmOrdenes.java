    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Selecciona una orden o escribe su código."
            );
            return;
        }

        boolean eliminado = lista.eliminar(codigo);

        if (!eliminado) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No existe una orden con ese código."
            );
            return;
        }

        mostrarOrdenes();
        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Orden eliminada correctamente."
        );        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (tblOrdenes.getSelectedRow() == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Selecciona la orden que deseas actualizar."
            );
            return;
        }

        String codigo = txtCodigo.getText().trim();
        String cliente = txtCliente.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String equipo = txtEquipo.getText().trim();
        String falla = txtFalla.getText().trim();
        String estado = (String) cmbEstado.getSelectedItem();

        if (codigo.isEmpty() || cliente.isEmpty() || telefono.isEmpty()
                || equipo.isEmpty() || falla.isEmpty()
                || estado == null || estado.trim().isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Completa todos los campos.",
                    "Datos incompletos",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        boolean actualizado = lista.actualizar(
                codigo, cliente, telefono, equipo, falla, estado
        );

        if (!actualizado) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No existe una orden con ese código."
            );
            return;
        }

        mostrarOrdenes();
        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Orden actualizada correctamente."
        );        // TODO add your handling code here:
    }//GEN-LAST:event_btnActualizarActionPerformed

