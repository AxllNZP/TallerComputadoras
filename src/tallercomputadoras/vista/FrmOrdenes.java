    private void configurarTabla() {
        String[] columnas = {
            "Código", "Cliente", "Teléfono",
            "Equipo", "Falla reportada", "Estado"
        };

        modeloTabla = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        tblOrdenes.setModel(modeloTabla);

        tblOrdenes.setSelectionMode(
                javax.swing.ListSelectionModel.SINGLE_SELECTION
        );

        tblOrdenes.getTableHeader().setReorderingAllowed(false);

        tblOrdenes.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                cargarSeleccion();
            }
        });
    }

    private void mostrarOrdenes() {
        modeloTabla.setRowCount(0);

        NodoOrden actual = lista.getPrimero();

        while (actual != null) {
            OrdenReparacion orden = actual.getOrden();

            modeloTabla.addRow(new Object[]{
                orden.getCodigo(),
                orden.getCliente(),
                orden.getTelefono(),
                orden.getEquipo(),
                orden.getFalla(),
                orden.getEstado()
            });

            actual = actual.getSiguiente();
        }
    }

    private void cargarSeleccion() {
        int fila = tblOrdenes.getSelectedRow();

        if (fila == -1) {
            return;
        }

        int filaModelo = tblOrdenes.convertRowIndexToModel(fila);

        String codigo = modeloTabla.getValueAt(
                filaModelo, 0
        ).toString();

        OrdenReparacion orden = lista.buscarPorCodigo(codigo);

        if (orden == null) {
            return;
        }

        txtCodigo.setText(orden.getCodigo());
        txtCliente.setText(orden.getCliente());
        txtTelefono.setText(orden.getTelefono());
        txtEquipo.setText(orden.getEquipo());
        txtFalla.setText(orden.getFalla());
        cmbEstado.setSelectedItem(orden.getEstado());

        txtCodigo.setEditable(false);
    }

    private void limpiarCampos() {
        tblOrdenes.clearSelection();

        txtCodigo.setEditable(true);
        txtCodigo.setText("");
        txtCliente.setText("");
        txtTelefono.setText("");
        txtEquipo.setText("");
        txtFalla.setText("");
        cmbEstado.setSelectedIndex(0);

        txtCodigo.requestFocusInWindow();
    }

