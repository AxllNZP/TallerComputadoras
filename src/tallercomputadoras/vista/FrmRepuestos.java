    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String codigo = txtCodigo.getText().trim()
                .toUpperCase(java.util.Locale.ROOT);

        String nombre = txtNombre.getText().trim();
        String textoStock = txtStock.getText().trim();

        if (codigo.isEmpty() || nombre.isEmpty() || textoStock.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Completa código, nombre y stock."
            );
            return;
        }

        int stock;

        try {
            stock = Integer.parseInt(textoStock);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(
                    this, "El stock debe ser un número entero válido."
            );
            return;
        }

        try {
            Repuesto repuesto = new Repuesto(codigo, nombre, stock);
            arbol.insertar(repuesto);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
            return;
        }

        mostrarRepuestos();
        limpiarCampos();

        JOptionPane.showMessageDialog(
                this, "Repuesto registrado correctamente."
        );        // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarActionPerformed

