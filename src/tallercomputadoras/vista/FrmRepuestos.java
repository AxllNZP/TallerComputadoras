    private void configurarTabla() {
        String[] columnas = {"Código", "Nombre", "Stock"};

        modeloTabla = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        tblRepuestos.setModel(modeloTabla);
        tblRepuestos.getTableHeader().setReorderingAllowed(false);
    }

    private void mostrarRepuestos() {
        modeloTabla.setRowCount(0);
        recorrerInorden(arbol.getRaiz());
    }

    private void recorrerInorden(NodoRepuesto nodo) {
        if (nodo == null) {
            return;
        }

        recorrerInorden(nodo.getIzquierda());

        Repuesto repuesto = nodo.getRepuesto();

        modeloTabla.addRow(new Object[]{
            repuesto.getCodigo(),
            repuesto.getNombre(),
            repuesto.getStock()
        });

        recorrerInorden(nodo.getDerecha());
    }

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtNombre.setText("");
        txtStock.setText("");
        txtBuscar.setText("");

        txtCodigo.requestFocusInWindow();
    }

    private void mostrarResultado(Repuesto repuesto) {
        if (repuesto == null) {
            JOptionPane.showMessageDialog(this, "Código no encontrado");
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                "Código: " + repuesto.getCodigo() + "\n"
                + "Nombre: " + repuesto.getNombre() + "\n"
                + "Stock: " + repuesto.getStock()
        );
    }

